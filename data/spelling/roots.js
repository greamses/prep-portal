/* ═══════════════════════════════════════════════════════
   SPELLING — the root of every word in the three spelling lists, keyed by the
   word in lower case, so a word in more than one list has one root.
     ROOTS[word] = [root, gloss]          a root word:  ['fortuitus', 'happening by chance']
     ROOTS[word] = [root, gloss, 1]       a name:       ['Ned Ludd', 'a weaver said to have smashed machines', 1]
   A root made of parts joins them with " + ", and its gloss gives the parts'
   meanings in the same order, split by commas ('hydor + kephale', 'water, head').
   No gloss contains its own headword.

   A spelling bee tells you the part of speech, the language of origin and the
   root when you ask. aboutLine() is what is SAID (Drills plays it as a Kokoro
   clip, kind 'o', made from this same function by tools/spelling-audio);
   aboutText() is what is shown. The card shows the root only once the word is
   done, because a root written out (fortuitus) nearly spells the word; a bee
   only ever says it.
═══════════════════════════════════════════════════════ */

const VOWEL = /^[aeiou]/i;
const article = (w) => (VOWEL.test(w) ? 'an' : 'a');

/** The language, without the bracket a root replaces: "English (from Ned Ludd)" -> "English".
    A bracket that adds something the root does not (through Greek, probably) is kept. */
export function language(origin, root = null) {
  if (!origin) return '';
  let o = origin.replace(/ name\b/g, '');
  if (root) o = o.replace(/\s*\((?!through|probably|Aboriginal|Algonquian)[^)]*\)/g, '');
  return o.trim();
}

const parts = (s, sep) => s.split(sep).map((p) => p.trim()).filter(Boolean);
const listed = (xs) => (xs.length < 2 ? xs.join('') : `${xs.slice(0, -1).join(', ')} and ${xs[xs.length - 1]}`);

/** The root as shown: "fortuitus, “happening by chance”" or "Ned Ludd, a weaver ...". */
export function rootText(word) {
  const r = ROOTS[String(word).toLowerCase()];
  if (!r) return '';
  const [root, gloss, name] = r;
  return name ? `${root}, ${gloss}` : `${root}, “${gloss}”`;
}

/** "noun · from Latin", plus the root when `withRoot`. */
export function aboutText(word, pos, origin, withRoot = false) {
  const r = ROOTS[String(word).toLowerCase()];
  const lang = language(origin, r && withRoot ? r[0] : null);
  return [pos, lang && `from ${lang}`, withRoot && rootText(word)].filter(Boolean).join(' · ');
}

/** What the boy SAYS: "It is an adjective, from Latin. The root is fortuitus, meaning happening by chance." */
export function aboutLine(word, pos, origin) {
  const r = ROOTS[String(word).toLowerCase()];
  const lang = language(origin, r ? r[0] : null).replace(/\s*\(([^)]*)\)/g, ', $1').replace(/ \+ /g, ' and ');
  const first = pos && lang ? `It is ${article(pos)} ${pos}, from ${lang}.`
    : pos ? `It is ${article(pos)} ${pos}.` : lang ? `It comes from ${lang}.` : '';
  if (!r) return first;
  const [root, gloss, name] = r;
  if (name) return `${first} It comes from ${root}, ${gloss}.`.trim();
  const bits = parts(root, '+');
  if (bits.length < 2) return `${first} The root is ${root}, meaning ${gloss}.`.trim();
  const means = parts(gloss, ',');
  const meaning = means.length === bits.length ? listed(means) : gloss;
  return `${first} The roots are ${listed(bits)}, meaning ${meaning}.`.trim();
}

